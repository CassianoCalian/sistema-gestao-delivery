-- ============================================================================
-- Depósito do Zé
-- Migration: estoque físico compartilhado
-- Data: 2026-09-18
--
-- Objetivo:
--   Permitir que vários formatos de venda (unidade, promoção, pack etc.)
--   consumam o mesmo estoque físico real.
--
-- Exemplo:
--   240 latões físicos de Brahma 473 ml
--   unidade -> consome 1  -> 240 vendas possíveis
--   promoção 5 -> consome 5 -> 48 vendas possíveis
--   pack 12 -> consome 12 -> 20 vendas possíveis
--
-- Observação:
--   Esta migration versiona a ESTRUTURA e a LÓGICA do recurso.
--   Ela não cadastra produtos específicos nem dados de estoque de produção.
-- ============================================================================


-- ============================================================================
-- 1. TABELAS
-- ============================================================================

create table if not exists public.estoques_compartilhados (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone not null default now(),
  nome text not null,
  quantidade_total integer not null default 0,
  constraint estoques_compartilhados_quantidade_total_check
    check (quantidade_total >= 0)
);

create unique index if not exists estoques_compartilhados_nome_unique
  on public.estoques_compartilhados (lower(nome));


create table if not exists public.produto_estoque_config (
  produto_id bigint primary key
    references public.produtos(id)
    on delete cascade,

  estoque_compartilhado_id bigint not null
    references public.estoques_compartilhados(id)
    on delete restrict,

  quantidade_por_venda integer not null default 1,

  constraint produto_estoque_config_quantidade_por_venda_check
    check (quantidade_por_venda > 0)
);

create index if not exists produto_estoque_config_estoque_idx
  on public.produto_estoque_config (estoque_compartilhado_id);


create table if not exists public.movimentacoes_estoque_compartilhado (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone not null default now(),

  estoque_compartilhado_id bigint not null
    references public.estoques_compartilhados(id)
    on delete restrict,

  pedido_id bigint null
    references public.pedidos(id)
    on delete set null,

  quantidade_anterior integer not null,
  quantidade_nova integer not null,
  unidades_consumidas integer not null default 0,
  observacao text null
);


