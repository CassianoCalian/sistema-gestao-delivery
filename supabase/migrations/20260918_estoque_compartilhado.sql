create or replace function public.atualizar_produto_admin(
  p_produto_id bigint,
  p_nome text,
  p_descricao text,
  p_categoria_id bigint,
  p_preco numeric,
  p_preco_promocional numeric,
  p_estoque integer,
  p_imagem_url text,
  p_ativo boolean,
  p_destaque boolean,
  p_em_promocao boolean,
  p_estoque_minimo integer,
  p_permite_abaixo_minimo boolean
)
returns table(
  id bigint,
  nome text,
  descricao text,
  preco numeric,
  preco_promocional numeric,
  estoque integer,
  estoque_minimo integer,
  imagem_url text,
  ativo boolean,
  destaque boolean,
  em_promocao boolean,
  permite_abaixo_minimo boolean,
  categoria_id bigint
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_estoque_anterior integer;
  v_estoque_final integer;
  v_diferenca integer;
  v_usa_estoque_compartilhado boolean;
begin
  if p_estoque is null or p_estoque < 0 then
    raise exception 'ESTOQUE_INVALIDO';
  end if;

  if p_estoque_minimo is null or p_estoque_minimo < 0 then
    raise exception 'ESTOQUE_MINIMO_INVALIDO';
  end if;

  select
    p.estoque,
    exists (
      select 1
      from public.produto_estoque_config c
      where c.produto_id = p.id
    )
  into
    v_estoque_anterior,
    v_usa_estoque_compartilhado
  from public.produtos p
  where p.id = p_produto_id
  for update;

  if not found then
    raise exception 'PRODUTO_NAO_ENCONTRADO';
  end if;

  if v_usa_estoque_compartilhado then
    v_estoque_final := v_estoque_anterior;
  else
    v_estoque_final := p_estoque;
  end if;

  v_diferenca :=
    v_estoque_final - v_estoque_anterior;

  update public.produtos p
  set
    nome = p_nome,
    descricao = p_descricao,
    categoria_id = p_categoria_id,
    preco = p_preco,
    preco_promocional = p_preco_promocional,
    estoque = v_estoque_final,
    estoque_minimo = p_estoque_minimo,
    imagem_url = p_imagem_url,
    ativo = p_ativo,
    destaque = p_destaque,
    em_promocao = p_em_promocao,
    permite_abaixo_minimo =
      coalesce(p_permite_abaixo_minimo, false)
  where p.id = p_produto_id;

  if not v_usa_estoque_compartilhado
     and v_diferenca <> 0 then
    insert into public.movimentacoes_estoque (
      produto_id,
      pedido_id,
      tipo,
      quantidade,
      estoque_anterior,
      estoque_novo,
      observacao
    )
    values (
      p_produto_id,
      null,
      'ajuste_manual',
      v_diferenca,
      v_estoque_anterior,
      v_estoque_final,
      'Ajuste manual pelo painel administrativo'
    );
  end if;

  return query
  select
    p.id,
    p.nome,
    p.descricao,
    p.preco,
    p.preco_promocional,
    p.estoque,
    p.estoque_minimo,
    p.imagem_url,
    p.ativo,
    p.destaque,
    p.em_promocao,
    p.permite_abaixo_minimo,
    p.categoria_id
  from public.produtos p
  where p.id = p_produto_id;
end;
$$;


-- ============================================================================
-- 11. CRIAÇÃO DE PEDIDO COM ESTOQUE COMPARTILHADO
-- ============================================================================

create or replace function public.criar_pedido_com_estoque_v2(
  p_nome text,
  p_telefone text,
  p_cep text,
  p_rua text,
  p_numero text,
  p_complemento text,
  p_bairro text,
  p_referencia text,
  p_forma_pagamento text,
  p_troco_para numeric,
  p_itens jsonb,
  p_pontos_fidelidade integer,
  p_codigo_cupom text,
  p_chave_idempotencia uuid
)
returns table(
  pedido_id bigint,
  codigo_acesso uuid,
  subtotal numeric,
  taxa_entrega numeric,
  total numeric
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pedido_existente record;
  v_resultado record;
begin
  if p_chave_idempotencia is null then
    raise exception 'CHAVE_IDEMPOTENCIA_INVALIDA';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended(
      p_chave_idempotencia::text,
      0
    )
  );

  select
    p.id,
    p.codigo_acesso,
    p.subtotal,
    p.taxa_entrega,
    p.total
  into v_pedido_existente
  from public.pedidos p
  where p.chave_idempotencia =
    p_chave_idempotencia
  limit 1;

  if found then
    return query
    select
      v_pedido_existente.id,
      v_pedido_existente.codigo_acesso,
      v_pedido_existente.subtotal,
      v_pedido_existente.taxa_entrega,
      v_pedido_existente.total;

    return;
  end if;

  perform e.id
  from public.estoques_compartilhados e
  where e.id in (
    select distinct
      c.estoque_compartilhado_id
    from public.produto_estoque_config c
    join jsonb_to_recordset(p_itens)
      as item(
        id bigint,
        quantidade integer,
        opcoes_selecionadas jsonb
      )
      on item.id = c.produto_id
  )
  order by e.id
  for update of e;

  select *
  into v_resultado
  from public.criar_pedido_com_estoque(
    p_nome,
    p_telefone,
    p_cep,
    p_rua,
    p_numero,
    p_complemento,
    p_bairro,
    p_referencia,
    p_forma_pagamento,
    p_troco_para,
    p_itens,
    p_pontos_fidelidade,
    p_codigo_cupom,
    p_chave_idempotencia
  );

  perform public.processar_estoque_compartilhado_pedido(
    p_itens,
    v_resultado.pedido_id
  );

  perform public.sincronizar_estoque_compartilhado(
    estoque_id
  )
  from (
    select distinct
      c.estoque_compartilhado_id as estoque_id
    from public.produto_estoque_config c
    join jsonb_to_recordset(p_itens)
      as item(
        id bigint,
        quantidade integer,
        opcoes_selecionadas jsonb
      )
      on item.id = c.produto_id
  ) estoques;

  return query
  select
    v_resultado.pedido_id,
    v_resultado.codigo_acesso,
    v_resultado.subtotal,
    v_resultado.taxa_entrega,
    v_resultado.total;
end;
$$;


-- ============================================================================
-- 12. CANCELAMENTO E REPOSIÇÃO
-- ============================================================================

create or replace function public.cancelar_pedido_repor_estoque(
  p_pedido_id bigint
)
returns table(
  id bigint,
  status text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_status text;
  v_cliente_id bigint;
  v_pontos_fidelidade_usados integer;
  v_desconto_fidelidade numeric(12, 2);
  v_cupom_id uuid;
  v_movimento record;
begin
  select
    p.status,
    p.cliente_id,
    coalesce(p.pontos_fidelidade_usados, 0),
    coalesce(p.desconto_fidelidade, 0),
    p.cupom_id
  into
    v_status,
    v_cliente_id,
    v_pontos_fidelidade_usados,
    v_desconto_fidelidade,
    v_cupom_id
  from public.pedidos as p
  where p.id = p_pedido_id
  for update;

  if not found then
    raise exception 'PEDIDO_NAO_ENCONTRADO';
  end if;

  if v_status = 'cancelado' then
    return query
    select
      p.id,
      p.status
    from public.pedidos as p
    where p.id = p_pedido_id;

    return;
  end if;

  if v_status = 'entregue' then
    raise exception
      'PEDIDO_ENTREGUE_NAO_PODE_SER_CANCELADO';
  end if;

  if v_pontos_fidelidade_usados > 0 then
    update public.clientes as c
    set pontos_saldo =
      c.pontos_saldo + v_pontos_fidelidade_usados
    where c.id = v_cliente_id;

    if not found then
      raise exception
        'CLIENTE_NAO_ENCONTRADO:%',
        v_cliente_id;
    end if;

    insert into public.fidelidade_movimentacoes (
      cliente_id,
      pedido_id,
      tipo,
      pontos,
      valor_referencia,
      observacao
    )
    values (
      v_cliente_id,
      p_pedido_id,
      'ajuste_credito',
      v_pontos_fidelidade_usados,
      v_desconto_fidelidade,
      'Estorno de fidelidade por cancelamento do pedido #'
        || p_pedido_id
    );
  end if;

  if v_cupom_id is not null then
    update public.cupons as c
    set
      ativo = (c.valido_ate > now()),
      usado_em = null,
      pedido_id_usado = null
    where c.id = v_cupom_id
      and c.pedido_id_usado = p_pedido_id;
  end if;

  for v_movimento in
    select
      m.estoque_compartilhado_id,
      sum(m.unidades_consumidas)::integer
        as unidades_devolver
    from public.movimentacoes_estoque_compartilhado as m
    where m.pedido_id = p_pedido_id
      and m.unidades_consumidas > 0
    group by m.estoque_compartilhado_id
    order by m.estoque_compartilhado_id
  loop
    declare
      v_quantidade_anterior integer;
      v_quantidade_nova integer;
    begin
      select
        e.quantidade_total
      into
        v_quantidade_anterior
      from public.estoques_compartilhados as e
      where e.id =
        v_movimento.estoque_compartilhado_id
      for update;

      if not found then
        raise exception
          'ESTOQUE_COMPARTILHADO_NAO_ENCONTRADO:%',
          v_movimento.estoque_compartilhado_id;
      end if;

      v_quantidade_nova :=
        v_quantidade_anterior
        + v_movimento.unidades_devolver;

      update public.estoques_compartilhados as e
      set quantidade_total =
        v_quantidade_nova
      where e.id =
        v_movimento.estoque_compartilhado_id;

      insert into public.movimentacoes_estoque_compartilhado (
        estoque_compartilhado_id,
        pedido_id,
        quantidade_anterior,
        quantidade_nova,
        unidades_consumidas,
        observacao
      )
      values (
        v_movimento.estoque_compartilhado_id,
        p_pedido_id,
        v_quantidade_anterior,
        v_quantidade_nova,
        0,
        'Cancelamento do pedido #'
          || p_pedido_id
          || ' | Devolução física: +'
          || v_movimento.unidades_devolver
          || ' unidades'
      );
    end;
  end loop;

  for v_movimento in
    select
      c.estoque_compartilhado_id,
      sum(
        ip.quantidade *
        c.quantidade_por_venda
      )::integer as unidades_devolver
    from public.itens_pedido as ip
    join public.produto_estoque_config as c
      on c.produto_id = ip.produto_id
    where ip.pedido_id = p_pedido_id
      and not exists (
        select 1
        from public.movimentacoes_estoque_compartilhado as m
        where m.pedido_id = p_pedido_id
          and m.estoque_compartilhado_id =
            c.estoque_compartilhado_id
          and m.unidades_consumidas > 0
      )
    group by c.estoque_compartilhado_id
    order by c.estoque_compartilhado_id
  loop
    declare
      v_quantidade_anterior integer;
      v_quantidade_nova integer;
    begin
      select
        e.quantidade_total
      into
        v_quantidade_anterior
      from public.estoques_compartilhados as e
      where e.id =
        v_movimento.estoque_compartilhado_id
      for update;

      if not found then
        raise exception
          'ESTOQUE_COMPARTILHADO_NAO_ENCONTRADO:%',
          v_movimento.estoque_compartilhado_id;
      end if;

      v_quantidade_nova :=
        v_quantidade_anterior
        + v_movimento.unidades_devolver;

      update public.estoques_compartilhados as e
      set quantidade_total =
        v_quantidade_nova
      where e.id =
        v_movimento.estoque_compartilhado_id;

      insert into public.movimentacoes_estoque_compartilhado (
        estoque_compartilhado_id,
        pedido_id,
        quantidade_anterior,
        quantidade_nova,
        unidades_consumidas,
        observacao
      )
      values (
        v_movimento.estoque_compartilhado_id,
        p_pedido_id,
        v_quantidade_anterior,
        v_quantidade_nova,
        0,
        'Cancelamento do pedido #'
          || p_pedido_id
          || ' | Devolução física de pedido legado: +'
          || v_movimento.unidades_devolver
          || ' unidades'
      );
    end;
  end loop;

  insert into public.movimentacoes_estoque (
    produto_id,
    pedido_id,
    tipo,
    quantidade,
    estoque_anterior,
    estoque_novo,
    observacao
  )
  select
    p.id,
    p_pedido_id,
    'cancelamento',
    itens.quantidade_total,
    p.estoque,
    p.estoque + itens.quantidade_total,
    'Cancelamento do pedido #'
      || p_pedido_id
  from public.produtos as p
  join (
    select
      ip.produto_id,
      sum(ip.quantidade)::integer
        as quantidade_total
    from public.itens_pedido as ip
    where ip.pedido_id = p_pedido_id
    group by ip.produto_id
  ) as itens
    on itens.produto_id = p.id
  left join public.produto_estoque_config as c
    on c.produto_id = p.id
  where c.produto_id is null;

  update public.produtos as p
  set estoque =
    p.estoque + itens.quantidade_total
  from (
    select
      ip.produto_id,
      sum(ip.quantidade)::integer
        as quantidade_total
    from public.itens_pedido as ip
    where ip.pedido_id = p_pedido_id
    group by ip.produto_id
  ) as itens
  left join public.produto_estoque_config as c
    on c.produto_id = itens.produto_id
  where p.id = itens.produto_id
    and c.produto_id is null;

  update public.pedidos as p
  set status = 'cancelado'
  where p.id = p_pedido_id;

  return query
  select
    p.id,
    p.status
  from public.pedidos as p
  where p.id = p_pedido_id;
end;
$$;


