after insert or delete or update
on public.produto_estoque_config
for each row
execute function public.trg_produto_estoque_config_sync();


-- ============================================================================
-- 6. PROCESSAMENTO DO ESTOQUE FÍSICO EM UMA VENDA
-- ============================================================================

create or replace function public.processar_estoque_compartilhado_pedido(
  p_itens jsonb,
  p_pedido_id bigint
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_demanda record;
  v_quantidade_anterior integer;
  v_quantidade_nova integer;
begin
  if p_itens is null
     or jsonb_typeof(p_itens) <> 'array' then
    raise exception
      'ITENS_ESTOQUE_COMPARTILHADO_INVALIDOS';
  end if;

  for v_demanda in
    with itens_agrupados as (
      select
        item.id as produto_id,
        sum(item.quantidade)::integer as quantidade
      from jsonb_to_recordset(p_itens)
        as item(
          id bigint,
          quantidade integer,
          opcoes_selecionadas jsonb
        )
      group by item.id
    )
    select
      c.estoque_compartilhado_id,
      sum(
        i.quantidade *
        c.quantidade_por_venda
      )::integer as unidades_necessarias
    from itens_agrupados i
    join public.produto_estoque_config c
      on c.produto_id = i.produto_id
    group by c.estoque_compartilhado_id
    order by c.estoque_compartilhado_id
  loop
    select e.quantidade_total
    into v_quantidade_anterior
    from public.estoques_compartilhados e
    where e.id =
      v_demanda.estoque_compartilhado_id
    for update;

    if not found then
      raise exception
        'ESTOQUE_COMPARTILHADO_NAO_ENCONTRADO:%',
        v_demanda.estoque_compartilhado_id;
    end if;

    if v_quantidade_anterior
       < v_demanda.unidades_necessarias then
      raise exception
        'ESTOQUE_COMPARTILHADO_INSUFICIENTE:%:%',
        v_demanda.estoque_compartilhado_id,
        v_quantidade_anterior;
    end if;

    v_quantidade_nova :=
      v_quantidade_anterior
      - v_demanda.unidades_necessarias;

    update public.estoques_compartilhados as e
    set quantidade_total =
      v_quantidade_nova
    where e.id =
      v_demanda.estoque_compartilhado_id;

    insert into public.movimentacoes_estoque_compartilhado (
      estoque_compartilhado_id,
      pedido_id,
      quantidade_anterior,
      quantidade_nova,
      unidades_consumidas,
      observacao
    )
    values (
      v_demanda.estoque_compartilhado_id,
      p_pedido_id,
      v_quantidade_anterior,
      v_quantidade_nova,
      v_demanda.unidades_necessarias,
      'Venda do pedido #' || p_pedido_id
    );
  end loop;
end;
$$;


-- ============================================================================
-- 7. ENTRADA DE MERCADORIA
-- ============================================================================

create or replace function public.registrar_entrada_estoque(
  p_produto_id bigint,
  p_quantidade integer,
  p_observacao text default null::text
)
returns table(
  produto_id bigint,
  estoque_anterior integer,
  estoque_novo integer
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_estoque_anterior integer;
  v_estoque_novo integer;
  v_estoque_compartilhado_id bigint;
  v_quantidade_por_venda integer;
  v_quantidade_base_anterior integer;
  v_quantidade_base_nova integer;
  v_quantidade_base_adicionada integer;
  v_observacao text;
begin
  if p_quantidade is null
     or p_quantidade <= 0 then
    raise exception 'QUANTIDADE_INVALIDA';
  end if;

  v_observacao :=
    coalesce(
      nullif(trim(p_observacao), ''),
      'Entrada de mercadoria'
    );

  select
    c.estoque_compartilhado_id,
    c.quantidade_por_venda
  into
    v_estoque_compartilhado_id,
    v_quantidade_por_venda
  from public.produtos p
  left join public.produto_estoque_config c
    on c.produto_id = p.id
  where p.id = p_produto_id;

  if not found then
    raise exception 'PRODUTO_NAO_ENCONTRADO';
  end if;

  if v_estoque_compartilhado_id is not null then
    select e.quantidade_total
    into v_quantidade_base_anterior
    from public.estoques_compartilhados e
    where e.id = v_estoque_compartilhado_id
    for update;

    if not found then
      raise exception
        'ESTOQUE_COMPARTILHADO_NAO_ENCONTRADO:%',
        v_estoque_compartilhado_id;
    end if;

    select p.estoque
    into v_estoque_anterior
    from public.produtos p
    where p.id = p_produto_id
    for update;

    v_quantidade_base_adicionada :=
      p_quantidade * v_quantidade_por_venda;

    v_quantidade_base_nova :=
      v_quantidade_base_anterior
      + v_quantidade_base_adicionada;

    update public.estoques_compartilhados as e
    set quantidade_total =
      v_quantidade_base_nova
    where e.id =
      v_estoque_compartilhado_id;

    select p.estoque
    into v_estoque_novo
    from public.produtos p
    where p.id = p_produto_id;

    insert into public.movimentacoes_estoque_compartilhado (
      estoque_compartilhado_id,
      pedido_id,
      quantidade_anterior,
      quantidade_nova,
      unidades_consumidas,
      observacao
    )
    values (
      v_estoque_compartilhado_id,
      null,
      v_quantidade_base_anterior,
      v_quantidade_base_nova,
      0,
      v_observacao
        || ' | Entrada física: +'
        || v_quantidade_base_adicionada
        || ' unidades'
    );

    insert into public.movimentacoes_estoque (
      produto_id,
      pedido_id,
      tipo,
      quantidade,
      estoque_anterior,
      estoque_novo,
      observacao
    )
    values (
      p_produto_id,
      null,
      'entrada',
      p_quantidade,
      v_estoque_anterior,
      v_estoque_novo,
      v_observacao
        || ' | Estoque compartilhado: +'
        || v_quantidade_base_adicionada
        || ' unidades físicas'
    );

    return query
    select
      p_produto_id,
      v_estoque_anterior,
      v_estoque_novo;

    return;
  end if;

  select p.estoque
  into v_estoque_anterior
  from public.produtos p
  where p.id = p_produto_id
  for update;

  if not found then
    raise exception 'PRODUTO_NAO_ENCONTRADO';
  end if;

  v_estoque_novo :=
    v_estoque_anterior
    + p_quantidade;

  insert into public.movimentacoes_estoque (
    produto_id,
    pedido_id,
    tipo,
    quantidade,
    estoque_anterior,
    estoque_novo,
    observacao
  )
  values (
    p_produto_id,
    null,
    'entrada',
    p_quantidade,
    v_estoque_anterior,
    v_estoque_novo,
    v_observacao
  );

  update public.produtos
  set estoque = v_estoque_novo
  where id = p_produto_id;

  return query
  select
    p_produto_id,
    v_estoque_anterior,
    v_estoque_novo;
end;
$$;


-- ============================================================================
-- 8. CADASTRO / EDIÇÃO DE ESTOQUE COMPARTILHADO PELO ADMIN
-- ============================================================================

create or replace function public.salvar_estoque_compartilhado_admin(
  p_estoque_id bigint,
  p_nome text,
  p_quantidade_total integer,
  p_vinculos jsonb
)
returns table(
  estoque_id bigint,
  nome text,
  quantidade_total integer
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_estoque_id bigint;
  v_quantidade_anterior integer := 0;
begin
  if nullif(trim(p_nome), '') is null then
    raise exception 'NOME_ESTOQUE_INVALIDO';
  end if;

  if p_quantidade_total is null
     or p_quantidade_total < 0 then
    raise exception 'QUANTIDADE_ESTOQUE_INVALIDA';
  end if;

  if p_vinculos is null
     or jsonb_typeof(p_vinculos) <> 'array' then
    raise exception 'VINCULOS_INVALIDOS';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_vinculos)
      as v(
        produto_id bigint,
        quantidade_por_venda integer
      )
    where v.produto_id is null
       or v.produto_id <= 0
       or v.quantidade_por_venda is null
       or v.quantidade_por_venda <= 0
  ) then
    raise exception 'VINCULO_INVALIDO';
  end if;

  if exists (
    select 1
    from (
      select
        v.produto_id,
        count(*) as quantidade
      from jsonb_to_recordset(p_vinculos)
        as v(
          produto_id bigint,
          quantidade_por_venda integer
        )
      group by v.produto_id
      having count(*) > 1
    ) duplicados
  ) then
    raise exception 'PRODUTO_DUPLICADO_NOS_VINCULOS';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_vinculos)
      as v(
        produto_id bigint,
        quantidade_por_venda integer
      )
    left join public.produtos p
      on p.id = v.produto_id
    where p.id is null
  ) then
    raise exception 'PRODUTO_NAO_ENCONTRADO';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_vinculos)
      as v(
        produto_id bigint,
        quantidade_por_venda integer
      )
    join public.produto_estoque_config c
      on c.produto_id = v.produto_id
    where p_estoque_id is null
       or c.estoque_compartilhado_id <> p_estoque_id
  ) then
    raise exception 'PRODUTO_JA_VINCULADO_OUTRO_ESTOQUE';
  end if;

  if p_estoque_id is null then
    insert into public.estoques_compartilhados (
      nome,
      quantidade_total
    )
    values (
      trim(p_nome),
      p_quantidade_total
    )
    returning id
    into v_estoque_id;

    v_quantidade_anterior := 0;
  else
    select e.quantidade_total
    into v_quantidade_anterior
    from public.estoques_compartilhados e
    where e.id = p_estoque_id
    for update;

    if not found then
      raise exception 'ESTOQUE_COMPARTILHADO_NAO_ENCONTRADO';
    end if;

    v_estoque_id := p_estoque_id;

    update public.estoques_compartilhados as e
    set
      nome = trim(p_nome),
      quantidade_total = p_quantidade_total
    where e.id = v_estoque_id;
  end if;

  delete from public.produto_estoque_config c
  where c.estoque_compartilhado_id = v_estoque_id
    and not exists (
      select 1
      from jsonb_to_recordset(p_vinculos)
        as v(
          produto_id bigint,
          quantidade_por_venda integer
        )
      where v.produto_id = c.produto_id
    );

  insert into public.produto_estoque_config (
    produto_id,
    estoque_compartilhado_id,
    quantidade_por_venda
  )
  select
    v.produto_id,
    v_estoque_id,
    v.quantidade_por_venda
  from jsonb_to_recordset(p_vinculos)
    as v(
      produto_id bigint,
      quantidade_por_venda integer
    )
  on conflict (produto_id)
  do update set
    estoque_compartilhado_id =
      excluded.estoque_compartilhado_id,
    quantidade_por_venda =
      excluded.quantidade_por_venda;

  perform public.sincronizar_estoque_compartilhado(
    v_estoque_id
  );

  if p_estoque_id is null
     or v_quantidade_anterior <> p_quantidade_total then
    insert into public.movimentacoes_estoque_compartilhado (
      estoque_compartilhado_id,
      pedido_id,
      quantidade_anterior,
      quantidade_nova,
      unidades_consumidas,
      observacao
    )
    values (
      v_estoque_id,
      null,
      v_quantidade_anterior,
      p_quantidade_total,
      0,
      case
        when p_estoque_id is null
        then 'Cadastro inicial do estoque físico'
        else 'Ajuste manual do estoque físico pelo administrador'
      end
    );
  end if;

  return query
  select
    e.id,
    e.nome,
    e.quantidade_total
  from public.estoques_compartilhados e
  where e.id = v_estoque_id;
end;
$$;


-- ============================================================================
-- 9. PROTEÇÃO GLOBAL DO ESTOQUE DERIVADO
-- ============================================================================

create or replace function public.proteger_estoque_derivado()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_estoque_calculado integer;
begin
  select
    (
      e.quantidade_total /
      c.quantidade_por_venda
    )::integer
  into v_estoque_calculado
  from public.produto_estoque_config c
  join public.estoques_compartilhados e
    on e.id = c.estoque_compartilhado_id
  where c.produto_id = new.id;

  if found then
    new.estoque := v_estoque_calculado;
  end if;

  return new;
end;
$$;


drop trigger if exists trg_proteger_estoque_derivado
  on public.produtos;

create trigger trg_proteger_estoque_derivado
before update of estoque
on public.produtos
for each row
execute function public.proteger_estoque_derivado();


