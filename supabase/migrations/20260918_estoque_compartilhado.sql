-- ============================================================================
-- 3. SINCRONIZAÇÃO DO ESTOQUE DERIVADO
-- ============================================================================

create or replace function public.sincronizar_estoque_compartilhado(
  p_estoque_id bigint
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.produtos as p
  set estoque =
    (
      e.quantidade_total /
      c.quantidade_por_venda
    )::integer
  from public.produto_estoque_config as c
  join public.estoques_compartilhados as e
    on e.id = c.estoque_compartilhado_id
  where
    p.id = c.produto_id
    and e.id = p_estoque_id;
end;
$$;


-- ============================================================================
-- 4. FUNÇÕES DOS TRIGGERS DE SINCRONIZAÇÃO
-- ============================================================================

create or replace function public.trg_sincronizar_estoque_compartilhado()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.sincronizar_estoque_compartilhado(new.id);
  return new;
end;
$$;


create or replace function public.trg_produto_estoque_config_sync()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'DELETE' then
    update public.produtos
    set estoque = 0
    where id = old.produto_id;

    perform public.sincronizar_estoque_compartilhado(
      old.estoque_compartilhado_id
    );

    return old;
  end if;

  if tg_op = 'UPDATE'
     and old.estoque_compartilhado_id
         <> new.estoque_compartilhado_id then
    perform public.sincronizar_estoque_compartilhado(
      old.estoque_compartilhado_id
    );
  end if;

  perform public.sincronizar_estoque_compartilhado(
    new.estoque_compartilhado_id
  );

  return new;
end;
$$;


