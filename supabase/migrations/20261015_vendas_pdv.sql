
-- DEPÓSITO DO ZÉ
-- Vendas presenciais do PDV
-- Não altera as funções de pedidos online.

BEGIN;

CREATE TABLE IF NOT EXISTS public.pdv_vendas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  chave_idempotencia uuid NOT NULL UNIQUE,
  cliente_id bigint NULL REFERENCES public.clientes(id) ON DELETE SET NULL,
  tipo_atendimento text NOT NULL DEFAULT 'balcao'
    CHECK (tipo_atendimento IN ('balcao')),
  forma_pagamento text NOT NULL
    CHECK (forma_pagamento IN ('pix', 'dinheiro', 'debito', 'credito')),
  pagamento_confirmado boolean NOT NULL DEFAULT true,
  troco_para numeric(12,2),
  subtotal numeric(12,2) NOT NULL CHECK (subtotal >= 0),
  taxa_cartao numeric(12,2) NOT NULL DEFAULT 0 CHECK (taxa_cartao >= 0),
  total numeric(12,2) NOT NULL CHECK (total >= 0),
  status text NOT NULL DEFAULT 'concluida'
    CHECK (status IN ('concluida', 'cancelada'))
);

CREATE TABLE IF NOT EXISTS public.pdv_venda_itens (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venda_id bigint NOT NULL
    REFERENCES public.pdv_vendas(id) ON DELETE RESTRICT,
  produto_id bigint NOT NULL
    REFERENCES public.produtos(id) ON DELETE RESTRICT,
  nome_produto text NOT NULL,
  preco_unitario numeric(12,2) NOT NULL,
  quantidade integer NOT NULL CHECK (quantidade > 0),
  subtotal numeric(12,2) NOT NULL
);

CREATE INDEX IF NOT EXISTS pdv_vendas_created_at_idx
  ON public.pdv_vendas(created_at DESC);

CREATE INDEX IF NOT EXISTS pdv_venda_itens_venda_idx
  ON public.pdv_venda_itens(venda_id);

ALTER TABLE public.pdv_vendas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pdv_venda_itens ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.pdv_vendas FROM anon, authenticated;
REVOKE ALL ON public.pdv_venda_itens FROM anon, authenticated;

GRANT ALL ON public.pdv_vendas TO service_role;
GRANT ALL ON public.pdv_venda_itens TO service_role;

GRANT USAGE, SELECT ON SEQUENCE
  public.pdv_vendas_id_seq,
  public.pdv_venda_itens_id_seq
TO service_role;

CREATE OR REPLACE FUNCTION public.registrar_venda_pdv(
  p_chave_idempotencia uuid,
  p_cliente_id bigint,
  p_forma_pagamento text,
  p_troco_para numeric,
  p_total_esperado numeric,
  p_itens jsonb
)
RETURNS TABLE(
  id_venda bigint,
  valor_subtotal numeric,
  valor_taxa_cartao numeric,
  valor_total numeric
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_venda_id bigint;
  v_subtotal numeric(12,2);
  v_taxa_cartao numeric(12,2);
  v_total numeric(12,2);
  v_demanda record;
BEGIN
  IF p_chave_idempotencia IS NULL THEN
    RAISE EXCEPTION 'CHAVE_INVALIDA';
  END IF;

  -- Impede que duas tentativas da mesma venda sejam executadas.
  PERFORM pg_advisory_xact_lock(
    hashtextextended('pdv:' || p_chave_idempotencia::text, 0)
  );

  SELECT v.id INTO v_venda_id
  FROM public.pdv_vendas v
  WHERE v.chave_idempotencia = p_chave_idempotencia;

  IF FOUND THEN
    RETURN QUERY
    SELECT v.id, v.subtotal, v.taxa_cartao, v.total
    FROM public.pdv_vendas v
    WHERE v.id = v_venda_id;

    RETURN;
  END IF;

  IF p_forma_pagamento IS NULL OR
     p_forma_pagamento NOT IN ('pix', 'dinheiro', 'debito', 'credito') THEN
    RAISE EXCEPTION 'PAGAMENTO_INVALIDO';
  END IF;

  IF p_itens IS NULL OR jsonb_typeof(p_itens) <> 'array' THEN
    RAISE EXCEPTION 'CARRINHO_INVALIDO';
  END IF;

  IF jsonb_array_length(p_itens) = 0 OR
     jsonb_array_length(p_itens) > 100 THEN
    RAISE EXCEPTION 'CARRINHO_INVALIDO';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(p_itens) AS i(
      id bigint,
      quantidade integer
    )
    WHERE i.id IS NULL OR i.id <= 0 OR
          i.quantidade IS NULL OR
          i.quantidade <= 0 OR i.quantidade > 999
  ) THEN
    RAISE EXCEPTION 'ITEM_INVALIDO';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(p_itens) AS i(
      id bigint,
      quantidade integer
    )
    GROUP BY i.id
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'ITEM_DUPLICADO';
  END IF;

  IF p_cliente_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.clientes c WHERE c.id = p_cliente_id
  ) THEN
    RAISE EXCEPTION 'CLIENTE_INVALIDO';
  END IF;

  -- Bloqueia os estoques físicos primeiro, na mesma ordem
  -- utilizada pelo processamento dos pedidos online.
  PERFORM e.id
  FROM public.estoques_compartilhados e
  WHERE e.id IN (
    SELECT DISTINCT c.estoque_compartilhado_id
    FROM public.produto_estoque_config c
    JOIN jsonb_to_recordset(p_itens) AS i(
      id bigint,
      quantidade integer
    ) ON i.id = c.produto_id
  )
  ORDER BY e.id
  FOR UPDATE OF e;

  -- Em seguida, bloqueia os produtos.
  PERFORM p.id
  FROM public.produtos p
  WHERE p.id IN (
    SELECT i.id
    FROM jsonb_to_recordset(p_itens) AS i(
      id bigint,
      quantidade integer
    )
  )
  ORDER BY p.id
  FOR UPDATE OF p;

  -- Confere se todos os produtos existem.
  IF (
    SELECT count(*)
    FROM public.produtos p
    WHERE p.id IN (
      SELECT i.id
      FROM jsonb_to_recordset(p_itens) AS i(
        id bigint,
        quantidade integer
      )
    )
  ) <> jsonb_array_length(p_itens) THEN
    RAISE EXCEPTION 'PRODUTO_NAO_ENCONTRADO';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.produtos p
    JOIN jsonb_to_recordset(p_itens) AS i(
      id bigint,
      quantidade integer
    ) ON i.id = p.id
    WHERE NOT p.ativo
  ) THEN
    RAISE EXCEPTION 'PRODUTO_INATIVO';
  END IF;

  -- Produtos com seleção de sabores não entram nesta
  -- primeira etapa de finalização do PDV.
  IF EXISTS (
    SELECT 1
    FROM public.produtos p
    JOIN jsonb_to_recordset(p_itens) AS i(
      id bigint,
      quantidade integer
    ) ON i.id = p.id
    WHERE coalesce(p.unidades_por_item, 0) > 0
  ) THEN
    RAISE EXCEPTION 'PRODUTO_COM_OPCOES';
  END IF;

  -- Confere o estoque de produtos não compartilhados.
  IF EXISTS (
    SELECT 1
    FROM public.produtos p
    JOIN jsonb_to_recordset(p_itens) AS i(
      id bigint,
      quantidade integer
    ) ON i.id = p.id
    LEFT JOIN public.produto_estoque_config c
      ON c.produto_id = p.id
    WHERE c.produto_id IS NULL
      AND p.estoque < i.quantidade
  ) THEN
    RAISE EXCEPTION 'ESTOQUE_INSUFICIENTE';
  END IF;

  -- Para estoque compartilhado, soma a demanda física
  -- de todos os produtos vinculados ao mesmo estoque.
  IF EXISTS (
    SELECT 1
    FROM (
      SELECT
        c.estoque_compartilhado_id,
        sum(i.quantidade * c.quantidade_por_venda)::integer
          AS quantidade_necessaria
      FROM jsonb_to_recordset(p_itens) AS i(
        id bigint,
        quantidade integer
      )
      JOIN public.produto_estoque_config c
        ON c.produto_id = i.id
      GROUP BY c.estoque_compartilhado_id
    ) demanda
    JOIN public.estoques_compartilhados e
      ON e.id = demanda.estoque_compartilhado_id
    WHERE e.quantidade_total < demanda.quantidade_necessaria
  ) THEN
    RAISE EXCEPTION 'ESTOQUE_COMPARTILHADO_INSUFICIENTE';
  END IF;

  -- Recalcula preços diretamente do banco.
  SELECT round(coalesce(sum(
    (
      CASE
        WHEN p.em_promocao
          AND p.preco_promocional IS NOT NULL
        THEN p.preco_promocional
        ELSE p.preco
      END
    ) * i.quantidade
  ), 0), 2)
  INTO v_subtotal
  FROM public.produtos p
  JOIN jsonb_to_recordset(p_itens) AS i(
    id bigint,
    quantidade integer
  ) ON i.id = p.id;

  -- Taxa de R$ 2 no crédito.
  v_taxa_cartao :=
    CASE WHEN p_forma_pagamento = 'credito' THEN 2 ELSE 0 END;

  v_total := v_subtotal + v_taxa_cartao;

  -- Impede registrar pagamento de valor desatualizado.
  IF p_total_esperado IS NULL OR
     round(p_total_esperado, 2) <> v_total THEN
    RAISE EXCEPTION 'TOTAL_ALTERADO';
  END IF;

  IF p_forma_pagamento = 'dinheiro' AND
     p_troco_para IS NOT NULL AND
     p_troco_para < v_total THEN
    RAISE EXCEPTION 'TROCO_INVALIDO';
  END IF;

  -- Cria a venda.
  INSERT INTO public.pdv_vendas (
    chave_idempotencia,
    cliente_id,
    tipo_atendimento,
    forma_pagamento,
    pagamento_confirmado,
    troco_para,
    subtotal,
    taxa_cartao,
    total,
    status
  )
  VALUES (
    p_chave_idempotencia,
    p_cliente_id,
    'balcao',
    p_forma_pagamento,
    true,
    CASE
      WHEN p_forma_pagamento = 'dinheiro'
      THEN p_troco_para
      ELSE NULL
    END,
    v_subtotal,
    v_taxa_cartao,
    v_total,
    'concluida'
  )
  RETURNING id INTO v_venda_id;

  -- Registra os itens com preços históricos.
  INSERT INTO public.pdv_venda_itens (
    venda_id,
    produto_id,
    nome_produto,
    preco_unitario,
    quantidade,
    subtotal
  )
  SELECT
    v_venda_id,
    p.id,
    p.nome,
    CASE
      WHEN p.em_promocao
        AND p.preco_promocional IS NOT NULL
      THEN p.preco_promocional
      ELSE p.preco
    END,
    i.quantidade,
    round((
      CASE
        WHEN p.em_promocao
          AND p.preco_promocional IS NOT NULL
        THEN p.preco_promocional
        ELSE p.preco
      END
    ) * i.quantidade, 2)
  FROM public.produtos p
  JOIN jsonb_to_recordset(p_itens) AS i(
    id bigint,
    quantidade integer
  ) ON i.id = p.id;

  -- Registra a movimentação no histórico dos produtos.
  INSERT INTO public.movimentacoes_estoque (
    produto_id,
    pedido_id,
    tipo,
    quantidade,
    estoque_anterior,
    estoque_novo,
    observacao
  )
  SELECT
    p.id,
    NULL,
    'venda',
    -i.quantidade,
    p.estoque,
    p.estoque - i.quantidade,
    'Venda presencial PDV #' || v_venda_id
  FROM public.produtos p
  JOIN jsonb_to_recordset(p_itens) AS i(
    id bigint,
    quantidade integer
  ) ON i.id = p.id;

  -- Baixa os produtos com estoque próprio.
  UPDATE public.produtos p
  SET estoque = p.estoque - i.quantidade
  FROM (
    SELECT item.id, item.quantidade
    FROM jsonb_to_recordset(p_itens) AS item(
      id bigint,
      quantidade integer
    )
    LEFT JOIN public.produto_estoque_config c
      ON c.produto_id = item.id
    WHERE c.produto_id IS NULL
  ) i
  WHERE p.id = i.id;

  -- Baixa o estoque físico compartilhado.
  -- O trigger existente sincroniza os estoques derivados.
  FOR v_demanda IN
    SELECT
      e.id AS estoque_id,
      e.quantidade_total AS quantidade_anterior,
      sum(i.quantidade * c.quantidade_por_venda)::integer
        AS unidades_consumidas
    FROM jsonb_to_recordset(p_itens) AS i(
      id bigint,
      quantidade integer
    )
    JOIN public.produto_estoque_config c
      ON c.produto_id = i.id
    JOIN public.estoques_compartilhados e
      ON e.id = c.estoque_compartilhado_id
    GROUP BY e.id, e.quantidade_total
    ORDER BY e.id
  LOOP
    UPDATE public.estoques_compartilhados e
    SET quantidade_total =
      e.quantidade_total - v_demanda.unidades_consumidas
    WHERE e.id = v_demanda.estoque_id;

    INSERT INTO public.movimentacoes_estoque_compartilhado (
      estoque_compartilhado_id,
      pedido_id,
      quantidade_anterior,
      quantidade_nova,
      unidades_consumidas,
      observacao
    )
    VALUES (
      v_demanda.estoque_id,
      NULL,
      v_demanda.quantidade_anterior,
      v_demanda.quantidade_anterior - v_demanda.unidades_consumidas,
      v_demanda.unidades_consumidas,
      'Venda presencial PDV #' || v_venda_id
    );
  END LOOP;

  RETURN QUERY
  SELECT
    v.id,
    v.subtotal,
    v.taxa_cartao,
    v.total
  FROM public.pdv_vendas v
  WHERE v.id = v_venda_id;
END;
$$;

REVOKE ALL ON FUNCTION public.registrar_venda_pdv(
  uuid, bigint, text, numeric, numeric, jsonb
) FROM PUBLIC, anon, authenticated;

GRANT EXECUTE ON FUNCTION public.registrar_venda_pdv(
  uuid, bigint, text, numeric, numeric, jsonb
) TO service_role;

COMMIT;
