-- DEPÓSITO DO ZÉ
-- Controle de turnos e movimentações de caixa
-- Etapa 1: não altera vendas nem estoque.

BEGIN;

CREATE TABLE IF NOT EXISTS public.pdv_caixas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo text NOT NULL UNIQUE,
  nome text NOT NULL,
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO public.pdv_caixas (codigo, nome)
VALUES ('principal', 'Caixa principal')
ON CONFLICT (codigo) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.pdv_turnos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  caixa_id bigint NOT NULL
    REFERENCES public.pdv_caixas(id),
  status text NOT NULL DEFAULT 'aberto'
    CHECK (status IN ('aberto', 'fechado')),
  aberto_em timestamptz NOT NULL DEFAULT now(),
  operador_abertura_id uuid NOT NULL,
  operador_abertura_email text NOT NULL,
  valor_inicial numeric(12,2) NOT NULL
    CHECK (valor_inicial >= 0),
  chave_abertura uuid NOT NULL UNIQUE,

  fechado_em timestamptz,
  operador_fechamento_id uuid,
  operador_fechamento_email text,
  valor_contado numeric(12,2)
    CHECK (valor_contado >= 0),
  observacao_fechamento text,
  chave_fechamento uuid UNIQUE
);

-- Apenas um turno aberto por caixa físico.
CREATE UNIQUE INDEX IF NOT EXISTS
  pdv_um_turno_aberto_por_caixa
ON public.pdv_turnos (caixa_id)
WHERE status = 'aberto';

CREATE INDEX IF NOT EXISTS pdv_turnos_historico_idx
ON public.pdv_turnos (caixa_id, aberto_em DESC);

CREATE TABLE IF NOT EXISTS public.pdv_caixa_movimentacoes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  turno_id bigint NOT NULL
    REFERENCES public.pdv_turnos(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  tipo text NOT NULL
    CHECK (tipo IN ('sangria', 'suprimento')),
  valor numeric(12,2) NOT NULL
    CHECK (valor > 0),
  motivo text NOT NULL,
  operador_id uuid NOT NULL,
  operador_email text NOT NULL,
  chave_idempotencia uuid NOT NULL UNIQUE
);

CREATE INDEX IF NOT EXISTS
  pdv_caixa_movimentacoes_turno_idx
ON public.pdv_caixa_movimentacoes (turno_id, created_at);

ALTER TABLE public.pdv_caixas
ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.pdv_turnos
ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.pdv_caixa_movimentacoes
ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.pdv_caixas
FROM PUBLIC, anon, authenticated;

REVOKE ALL ON public.pdv_turnos
FROM PUBLIC, anon, authenticated;

REVOKE ALL ON public.pdv_caixa_movimentacoes
FROM PUBLIC, anon, authenticated;

GRANT ALL ON public.pdv_caixas TO service_role;
GRANT ALL ON public.pdv_turnos TO service_role;
GRANT ALL ON public.pdv_caixa_movimentacoes TO service_role;

GRANT USAGE, SELECT ON SEQUENCE
  public.pdv_caixas_id_seq,
  public.pdv_turnos_id_seq,
  public.pdv_caixa_movimentacoes_id_seq
TO service_role;

-- ABERTURA DE TURNO
CREATE OR REPLACE FUNCTION public.abrir_turno_pdv(
  p_caixa_codigo text,
  p_valor_inicial numeric,
  p_operador_uid uuid,
  p_operador_email text,
  p_chave uuid
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_caixa_id bigint;
  v_turno_id bigint;
BEGIN
  IF p_chave IS NULL OR p_operador_uid IS NULL
     OR nullif(trim(p_operador_email), '') IS NULL THEN
    RAISE EXCEPTION 'DADOS_INVALIDOS';
  END IF;

  IF p_valor_inicial IS NULL
     OR p_valor_inicial < 0
     OR p_valor_inicial <> round(p_valor_inicial, 2) THEN
    RAISE EXCEPTION 'VALOR_INVALIDO';
  END IF;

  SELECT t.id INTO v_turno_id
  FROM public.pdv_turnos t
  WHERE t.chave_abertura = p_chave;

  IF FOUND THEN
    RETURN v_turno_id;
  END IF;

  SELECT c.id INTO v_caixa_id
  FROM public.pdv_caixas c
  WHERE c.codigo = p_caixa_codigo
    AND c.ativo = true
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'CAIXA_NAO_ENCONTRADO';
  END IF;

  -- Reconfere depois de bloquear o caixa.
  SELECT t.id INTO v_turno_id
  FROM public.pdv_turnos t
  WHERE t.chave_abertura = p_chave;

  IF FOUND THEN
    RETURN v_turno_id;
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.pdv_turnos t
    WHERE t.caixa_id = v_caixa_id
      AND t.status = 'aberto'
  ) THEN
    RAISE EXCEPTION 'CAIXA_JA_ABERTO';
  END IF;

  INSERT INTO public.pdv_turnos (
    caixa_id,
    operador_abertura_id,
    operador_abertura_email,
    valor_inicial,
    chave_abertura
  )
  VALUES (
    v_caixa_id,
    p_operador_uid,
    lower(trim(p_operador_email)),
    p_valor_inicial,
    p_chave
  )
  RETURNING id INTO v_turno_id;

  RETURN v_turno_id;
END;
$$;

-- SANGRIA E SUPRIMENTO
CREATE OR REPLACE FUNCTION public.movimentar_caixa_pdv(
  p_turno_id bigint,
  p_tipo text,
  p_valor numeric,
  p_motivo text,
  p_operador_uid uuid,
  p_operador_email text,
  p_chave uuid
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_status text;
  v_movimento_id bigint;
  v_turno_anterior bigint;
BEGIN
  IF p_chave IS NULL OR p_operador_uid IS NULL
     OR nullif(trim(p_operador_email), '') IS NULL THEN
    RAISE EXCEPTION 'DADOS_INVALIDOS';
  END IF;

  IF p_tipo NOT IN ('sangria', 'suprimento')
     OR p_tipo IS NULL THEN
    RAISE EXCEPTION 'TIPO_INVALIDO';
  END IF;

  IF p_valor IS NULL OR p_valor <= 0
     OR p_valor <> round(p_valor, 2) THEN
    RAISE EXCEPTION 'VALOR_INVALIDO';
  END IF;

  IF length(trim(coalesce(p_motivo, ''))) < 3 THEN
    RAISE EXCEPTION 'MOTIVO_OBRIGATORIO';
  END IF;

  SELECT t.status INTO v_status
  FROM public.pdv_turnos t
  WHERE t.id = p_turno_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'TURNO_NAO_ENCONTRADO';
  END IF;

  SELECT m.id, m.turno_id
  INTO v_movimento_id, v_turno_anterior
  FROM public.pdv_caixa_movimentacoes m
  WHERE m.chave_idempotencia = p_chave;

  IF FOUND THEN
    IF v_turno_anterior <> p_turno_id THEN
      RAISE EXCEPTION 'CHAVE_REUTILIZADA';
    END IF;

    RETURN v_movimento_id;
  END IF;

  IF v_status <> 'aberto' THEN
    RAISE EXCEPTION 'TURNO_JA_FECHADO';
  END IF;

  INSERT INTO public.pdv_caixa_movimentacoes (
    turno_id,
    tipo,
    valor,
    motivo,
    operador_id,
    operador_email,
    chave_idempotencia
  )
  VALUES (
    p_turno_id,
    p_tipo,
    p_valor,
    trim(p_motivo),
    p_operador_uid,
    lower(trim(p_operador_email)),
    p_chave
  )
  RETURNING id INTO v_movimento_id;

  RETURN v_movimento_id;
END;
$$;

-- FECHAMENTO DE TURNO
CREATE OR REPLACE FUNCTION public.fechar_turno_pdv(
  p_turno_id bigint,
  p_valor_contado numeric,
  p_observacao text,
  p_operador_uid uuid,
  p_operador_email text,
  p_chave uuid
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_status text;
  v_chave_anterior uuid;
BEGIN
  IF p_chave IS NULL OR p_operador_uid IS NULL
     OR nullif(trim(p_operador_email), '') IS NULL THEN
    RAISE EXCEPTION 'DADOS_INVALIDOS';
  END IF;

  IF p_valor_contado IS NULL
     OR p_valor_contado < 0
     OR p_valor_contado <> round(p_valor_contado, 2) THEN
    RAISE EXCEPTION 'VALOR_INVALIDO';
  END IF;

  SELECT t.status, t.chave_fechamento
  INTO v_status, v_chave_anterior
  FROM public.pdv_turnos t
  WHERE t.id = p_turno_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'TURNO_NAO_ENCONTRADO';
  END IF;

  IF v_status = 'fechado' THEN
    IF v_chave_anterior = p_chave THEN
      RETURN p_turno_id;
    END IF;

    RAISE EXCEPTION 'TURNO_JA_FECHADO';
  END IF;

  UPDATE public.pdv_turnos
  SET
    status = 'fechado',
    fechado_em = now(),
    operador_fechamento_id = p_operador_uid,
    operador_fechamento_email =
      lower(trim(p_operador_email)),
    valor_contado = p_valor_contado,
    observacao_fechamento =
      nullif(trim(coalesce(p_observacao, '')), ''),
    chave_fechamento = p_chave
  WHERE id = p_turno_id;

  RETURN p_turno_id;
END;
$$;

-- Somente o servidor com service_role
-- poderá executar essas operações.

REVOKE ALL ON FUNCTION public.abrir_turno_pdv(
  text, numeric, uuid, text, uuid
) FROM PUBLIC, anon, authenticated;

REVOKE ALL ON FUNCTION public.movimentar_caixa_pdv(
  bigint, text, numeric, text, uuid, text, uuid
) FROM PUBLIC, anon, authenticated;

REVOKE ALL ON FUNCTION public.fechar_turno_pdv(
  bigint, numeric, text, uuid, text, uuid
) FROM PUBLIC, anon, authenticated;

GRANT EXECUTE ON FUNCTION public.abrir_turno_pdv(
  text, numeric, uuid, text, uuid
) TO service_role;

GRANT EXECUTE ON FUNCTION public.movimentar_caixa_pdv(
  bigint, text, numeric, text, uuid, text, uuid
) TO service_role;

GRANT EXECUTE ON FUNCTION public.fechar_turno_pdv(
  bigint, numeric, text, uuid, text, uuid
) TO service_role;

COMMIT;