CREATE OR REPLACE FUNCTION public.criar_pedido_com_estoque(
  p_nome text,
  p_telefone text,
  p_cep text,
  p_rua text,
  p_numero text,
  p_complemento text,
  p_bairro text,
  p_referencia text,
  p_forma_pagamento text,
  p_troco_para numeric,
  p_itens jsonb,
  p_pontos_fidelidade integer,
  p_chave_idempotencia uuid
)
RETURNS TABLE(
  pedido_id bigint,
  codigo_acesso uuid,
  subtotal numeric,
  taxa_entrega numeric,
  total numeric
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_pedido_existente record;

  v_resultado record;
BEGIN

  IF p_chave_idempotencia IS NULL THEN

    RAISE EXCEPTION
      'CHAVE_IDEMPOTENCIA_INVALIDA';

  END IF;


  ----------------------------------------------------
  -- Trava chave de idempotência
  ----------------------------------------------------

  PERFORM pg_advisory_xact_lock(
    hashtextextended(
      p_chave_idempotencia::text,
      0
    )
  );


  ----------------------------------------------------
  -- Procura pedido existente
  ----------------------------------------------------

  SELECT
    p.id,
    p.codigo_acesso,
    p.subtotal,
    p.taxa_entrega,
    p.total

  INTO v_pedido_existente

  FROM public.pedidos p

  WHERE p.chave_idempotencia =
    p_chave_idempotencia

  LIMIT 1;


  IF FOUND THEN

    RETURN QUERY
    SELECT
      v_pedido_existente.id,
      v_pedido_existente.codigo_acesso,
      v_pedido_existente.subtotal,
      v_pedido_existente.taxa_entrega,
      v_pedido_existente.total;

    RETURN;

  END IF;


  ----------------------------------------------------
  -- Cria com fidelidade
  ----------------------------------------------------

  SELECT *
  INTO v_resultado
  FROM public.criar_pedido_com_estoque(
    p_nome,
    p_telefone,
    p_cep,
    p_rua,
    p_numero,
    p_complemento,
    p_bairro,
    p_referencia,
    p_forma_pagamento,
    p_troco_para,
    p_itens,
    p_pontos_fidelidade
  );


  ----------------------------------------------------
  -- Vincula chave ao pedido
  ----------------------------------------------------

  UPDATE public.pedidos
  SET chave_idempotencia =
    p_chave_idempotencia
  WHERE id = v_resultado.pedido_id;


  ----------------------------------------------------
  -- Retorno
  ----------------------------------------------------

  RETURN QUERY
  SELECT
    v_resultado.pedido_id,
    v_resultado.codigo_acesso,
    v_resultado.subtotal,
    v_resultado.taxa_entrega,
    v_resultado.total;

END;
$function$;


