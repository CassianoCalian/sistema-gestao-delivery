-- ============================================================
-- 9. FUNÇÃO DE CRÉDITO AUTOMÁTICO
-- ============================================================
-- Executada quando o pedido entra em "entregue".
--
-- Pontua somente:
--
-- subtotal - desconto_fidelidade
--
-- Taxa de cartão e outras taxas não geram pontos.
-- ============================================================

CREATE OR REPLACE FUNCTION public.processar_fidelidade_pedido_entregue()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_progresso_atual integer;

  v_valor_pedido_centavos integer;

  v_total_acumulado_centavos integer;

  v_pontos_gerados integer;

  v_novo_progresso integer;
BEGIN

  ----------------------------------------------------
  -- Só processa quando entra em "entregue"
  ----------------------------------------------------

  IF NEW.status <> 'entregue'
     OR OLD.status = 'entregue' THEN

    RETURN NEW;

  END IF;


  ----------------------------------------------------
  -- Bloqueia cliente durante o cálculo
  ----------------------------------------------------

  SELECT fidelidade_progresso_centavos
  INTO v_progresso_atual
  FROM public.clientes
  WHERE id = NEW.cliente_id
  FOR UPDATE;


  IF NOT FOUND THEN

    RAISE EXCEPTION
      'CLIENTE_NAO_ENCONTRADO:%',
      NEW.cliente_id;

  END IF;


  ----------------------------------------------------
  -- Impede que um pedido gere pontos duas vezes
  ----------------------------------------------------

  IF EXISTS (
    SELECT 1
    FROM public.fidelidade_movimentacoes
    WHERE pedido_id = NEW.id
      AND tipo = 'credito_pedido'
  ) THEN

    RETURN NEW;

  END IF;


  ----------------------------------------------------
  -- Valor efetivamente pago pelos produtos
  ----------------------------------------------------

  v_valor_pedido_centavos :=
    ROUND(
      GREATEST(
        COALESCE(NEW.subtotal, 0)
        - COALESCE(NEW.desconto_fidelidade, 0),
        0
      ) * 100
    )::integer;


  ----------------------------------------------------
  -- Soma resto anterior
  ----------------------------------------------------

  v_total_acumulado_centavos :=
    v_progresso_atual
    + v_valor_pedido_centavos;


  ----------------------------------------------------
  -- R$ 5,00 = 1 ponto
  ----------------------------------------------------

  v_pontos_gerados :=
    FLOOR(
      v_total_acumulado_centavos::numeric / 500
    )::integer;


  ----------------------------------------------------
  -- Guarda resto abaixo de R$ 5
  ----------------------------------------------------

  v_novo_progresso :=
    MOD(
      v_total_acumulado_centavos,
      500
    );


  ----------------------------------------------------
  -- Atualiza cliente
  ----------------------------------------------------

  UPDATE public.clientes
  SET
    pontos_saldo =
      pontos_saldo + v_pontos_gerados,

    fidelidade_progresso_centavos =
      v_novo_progresso

  WHERE id = NEW.cliente_id;


  ----------------------------------------------------
  -- Registra extrato
  ----------------------------------------------------

  INSERT INTO public.fidelidade_movimentacoes (
    cliente_id,
    pedido_id,
    tipo,
    pontos,
    valor_referencia,
    observacao
  )
  VALUES (
    NEW.cliente_id,
    NEW.id,
    'credito_pedido',
    v_pontos_gerados,

    GREATEST(
      COALESCE(NEW.subtotal, 0)
      - COALESCE(NEW.desconto_fidelidade, 0),
      0
    ),

    'Crédito de fidelidade do pedido #'
      || NEW.id
  );


  RETURN NEW;

END;
$function$;


-- ============================================================
-- 10. TRIGGER AO ENTREGAR PEDIDO
-- ============================================================

DROP TRIGGER IF EXISTS
trg_fidelidade_pedido_entregue
ON public.pedidos;


CREATE TRIGGER trg_fidelidade_pedido_entregue
AFTER UPDATE OF status
ON public.pedidos
FOR EACH ROW
WHEN (
  OLD.status IS DISTINCT FROM NEW.status
  AND NEW.status = 'entregue'
)
EXECUTE FUNCTION
public.processar_fidelidade_pedido_entregue();


-- ============================================================
-- 11. FUNÇÃO ADMINISTRATIVA DE RESGATE
-- ============================================================
-- 500 pontos = R$ 5,00
--
-- Não será chamada diretamente pelo checkout.
-- O checkout utiliza o resgate transacional junto ao pedido.
-- ============================================================

CREATE OR REPLACE FUNCTION public.resgatar_pontos_fidelidade(
  p_cliente_id bigint,
  p_pontos_resgatar integer
)
RETURNS TABLE(
  cliente_id bigint,
  pontos_resgatados integer,
  valor_desconto numeric,
  saldo_pontos integer
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_saldo_atual integer;

  v_novo_saldo integer;

  v_valor_desconto numeric(12, 2);
BEGIN

  IF p_pontos_resgatar IS NULL
     OR p_pontos_resgatar <= 0 THEN

    RAISE EXCEPTION
      'PONTOS_RESGATE_INVALIDOS';

  END IF;


  IF MOD(p_pontos_resgatar, 500) <> 0 THEN

    RAISE EXCEPTION
      'PONTOS_RESGATE_DEVE_SER_MULTIPLO_DE_500';

  END IF;


  SELECT pontos_saldo
  INTO v_saldo_atual
  FROM public.clientes
  WHERE id = p_cliente_id
  FOR UPDATE;


  IF NOT FOUND THEN

    RAISE EXCEPTION
      'CLIENTE_NAO_ENCONTRADO:%',
      p_cliente_id;

  END IF;


  IF v_saldo_atual < p_pontos_resgatar THEN

    RAISE EXCEPTION
      'SALDO_PONTOS_INSUFICIENTE:%:%',
      v_saldo_atual,
      p_pontos_resgatar;

  END IF;


  v_valor_desconto :=
    (p_pontos_resgatar / 500) * 5;


  v_novo_saldo :=
    v_saldo_atual - p_pontos_resgatar;


  UPDATE public.clientes
  SET pontos_saldo = v_novo_saldo
  WHERE id = p_cliente_id;


  INSERT INTO public.fidelidade_movimentacoes (
    cliente_id,
    pedido_id,
    tipo,
    pontos,
    valor_referencia,
    observacao
  )
  VALUES (
    p_cliente_id,
    NULL,
    'resgate',
    -p_pontos_resgatar,
    v_valor_desconto,

    'Resgate de fidelidade: R$ '
      || to_char(
        v_valor_desconto,
        'FM999999990.00'
      )
      || ' de desconto'
  );


  RETURN QUERY
  SELECT
    p_cliente_id,
    p_pontos_resgatar,
    v_valor_desconto,
    v_novo_saldo;

END;
$function$;


-- ============================================================
-- 11.1. CORREÇÃO DA FUNÇÃO PRINCIPAL DE PEDIDOS
-- ============================================================
-- Cliente existente mantém o nome canônico do CRM.
-- O nome informado no checkout continua salvo em pedidos.nome_cliente.
-- ============================================================

CREATE OR REPLACE FUNCTION public.criar_pedido_com_estoque(p_nome text, p_telefone text, p_cep text, p_rua text, p_numero text, p_complemento text, p_bairro text, p_referencia text, p_forma_pagamento text, p_troco_para numeric, p_itens jsonb)
 RETURNS TABLE(pedido_id bigint, codigo_acesso uuid, subtotal numeric, taxa_entrega numeric, total numeric)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_cliente_id bigint;
  v_pedido_id bigint;
  v_codigo_acesso uuid;

  v_subtotal numeric := 0;
  v_taxa_entrega numeric := 0;
  v_taxa_cartao numeric := 0;
  v_total numeric := 0;

  v_permite_abaixo_minimo boolean := false;

  v_quantidade_solicitada integer;
  v_quantidade_encontrada integer;

  v_nome_produto text;
  v_estoque_disponivel integer;
  v_quantidade_produto integer;
begin

  ----------------------------------------------------
  -- 1. Valida os itens
  ----------------------------------------------------

  if p_itens is null
     or jsonb_typeof(p_itens) <> 'array'
     or jsonb_array_length(p_itens) = 0 then

    raise exception 'CARRINHO_VAZIO';

  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_itens)
      as item(id bigint, quantidade integer)
    where item.id is null
       or item.quantidade is null
       or item.quantidade <= 0
  ) then

    raise exception 'ITEM_INVALIDO';

  end if;


  ----------------------------------------------------
  -- 2. Bloqueia os produtos
  ----------------------------------------------------

  perform p.id
  from produtos p
  join (
    select
      item.id as produto_id,
      sum(item.quantidade)::integer as quantidade
    from jsonb_to_recordset(p_itens)
      as item(id bigint, quantidade integer)
    group by item.id
  ) itens
    on itens.produto_id = p.id
  order by p.id
  for update of p;


  ----------------------------------------------------
  -- 3. Confere se todos existem
  ----------------------------------------------------

  select count(*)
  into v_quantidade_solicitada
  from (
    select distinct item.id
    from jsonb_to_recordset(p_itens)
      as item(id bigint, quantidade integer)
  ) solicitados;

  select count(*)
  into v_quantidade_encontrada
  from produtos p
  join (
    select distinct item.id
    from jsonb_to_recordset(p_itens)
      as item(id bigint, quantidade integer)
  ) solicitados
    on solicitados.id = p.id;

  if v_quantidade_encontrada <> v_quantidade_solicitada then
    raise exception 'PRODUTO_NAO_ENCONTRADO';
  end if;


  ----------------------------------------------------
  -- 4. Confere produtos inativos
  ----------------------------------------------------

  select p.nome
  into v_nome_produto
  from produtos p
  join (
    select distinct item.id
    from jsonb_to_recordset(p_itens)
      as item(id bigint, quantidade integer)
  ) solicitados
    on solicitados.id = p.id
  where p.ativo = false
  limit 1;

  if found then
    raise exception 'PRODUTO_INATIVO:%', v_nome_produto;
  end if;


  ----------------------------------------------------
  -- 5. Confere estoque
  ----------------------------------------------------

  select
    p.nome,
    p.estoque,
    itens.quantidade
  into
    v_nome_produto,
    v_estoque_disponivel,
    v_quantidade_produto
  from produtos p
  join (
    select
      item.id as produto_id,
      sum(item.quantidade)::integer as quantidade
    from jsonb_to_recordset(p_itens)
      as item(id bigint, quantidade integer)
    group by item.id
  ) itens
    on itens.produto_id = p.id
  where p.estoque < itens.quantidade
  limit 1;

  if found then
    raise exception
      'ESTOQUE_INSUFICIENTE:%:%',
      v_nome_produto,
      v_estoque_disponivel;
  end if;


  ----------------------------------------------------
  -- 6. Calcula subtotal
  ----------------------------------------------------

  select coalesce(
    sum(
      (
        case
          when p.em_promocao = true
            and p.preco_promocional is not null
          then p.preco_promocional
          else p.preco
        end
      ) * itens.quantidade
    ),
    0
  )
  into v_subtotal
  from produtos p
  join (
    select
      item.id as produto_id,
      sum(item.quantidade)::integer as quantidade
    from jsonb_to_recordset(p_itens)
      as item(id bigint, quantidade integer)
    group by item.id
  ) itens
    on itens.produto_id = p.id;


  ----------------------------------------------------
  -- 7. Verifica exceção ao pedido mínimo
  ----------------------------------------------------

  select coalesce(
    bool_or(p.permite_abaixo_minimo),
    false
  )
  into v_permite_abaixo_minimo
  from produtos p
  join (
    select distinct item.id as produto_id
    from jsonb_to_recordset(p_itens)
      as item(id bigint, quantidade integer)
  ) itens
    on itens.produto_id = p.id;


  ----------------------------------------------------
  -- 8. Valida pedido mínimo
  ----------------------------------------------------

  if v_subtotal < 30
     and not v_permite_abaixo_minimo then

    raise exception 'PEDIDO_MINIMO:30';

  end if;


  ----------------------------------------------------
  -- 9. Calcula taxas e total
  ----------------------------------------------------

  v_taxa_entrega := 0;

  if p_forma_pagamento = 'cartao_entrega' then
    v_taxa_cartao := 2;
  else
    v_taxa_cartao := 0;
  end if;

  v_total :=
    v_subtotal
    + v_taxa_entrega
    + v_taxa_cartao;


  ----------------------------------------------------
  -- 10. Reutiliza ou cria cliente pelo telefone
  ----------------------------------------------------

  insert into clientes as c (
    nome,
    telefone
  )
  values (
    trim(p_nome),
    trim(p_telefone)
  )
  on conflict (telefone_normalizado)
  do update
  set
    telefone = excluded.telefone
  returning c.id
  into v_cliente_id;


  ----------------------------------------------------
  -- 11. Cria pedido
  ----------------------------------------------------

  insert into pedidos (
    cliente_id,
    nome_cliente,
    telefone,
    cep,
    rua,
    numero,
    complemento,
    bairro,
    referencia,
    forma_pagamento,
    troco_para,
    subtotal,
    taxa_entrega,
    taxa_cartao,
    total,
    status
  )
  values (
    v_cliente_id,
    trim(p_nome),
    trim(p_telefone),
    trim(p_cep),
    trim(p_rua),
    trim(p_numero),
    nullif(trim(p_complemento), ''),
    trim(p_bairro),
    nullif(trim(p_referencia), ''),
    p_forma_pagamento,

    case
      when p_forma_pagamento = 'dinheiro'
      then p_troco_para
      else null
    end,

    v_subtotal,
    v_taxa_entrega,
    v_taxa_cartao,
    v_total,
    'recebido'
  )
  returning
    id,
    pedidos.codigo_acesso
  into
    v_pedido_id,
    v_codigo_acesso;


  ----------------------------------------------------
  -- 12. Salva itens do pedido
  ----------------------------------------------------

  insert into itens_pedido (
    pedido_id,
    produto_id,
    nome_produto,
    preco_unitario,
    quantidade,
    subtotal
  )
  select
    v_pedido_id,
    p.id,
    p.nome,

    case
      when p.em_promocao = true
        and p.preco_promocional is not null
      then p.preco_promocional
      else p.preco
    end,

    itens.quantidade,

    (
      case
        when p.em_promocao = true
          and p.preco_promocional is not null
        then p.preco_promocional
        else p.preco
      end
    ) * itens.quantidade

  from produtos p
  join (
    select
      item.id as produto_id,
      sum(item.quantidade)::integer as quantidade
    from jsonb_to_recordset(p_itens)
      as item(id bigint, quantidade integer)
    group by item.id
  ) itens
    on itens.produto_id = p.id;


  ----------------------------------------------------
  -- 13. Registra a venda no histórico
  ----------------------------------------------------

  insert into movimentacoes_estoque (
    produto_id,
    pedido_id,
    tipo,
    quantidade,
    estoque_anterior,
    estoque_novo,
    observacao
  )
  select
    p.id,
    v_pedido_id,
    'venda',
    -itens.quantidade,
    p.estoque,
    p.estoque - itens.quantidade,
    'Venda do pedido #' || v_pedido_id

  from produtos p
  join (
    select
      item.id as produto_id,
      sum(item.quantidade)::integer as quantidade
    from jsonb_to_recordset(p_itens)
      as item(id bigint, quantidade integer)
    group by item.id
  ) itens
    on itens.produto_id = p.id;


  ----------------------------------------------------
  -- 14. Baixa o estoque
  ----------------------------------------------------

  update produtos p
  set estoque = p.estoque - itens.quantidade
  from (
    select
      item.id as produto_id,
      sum(item.quantidade)::integer as quantidade
    from jsonb_to_recordset(p_itens)
      as item(id bigint, quantidade integer)
    group by item.id
  ) itens
  where p.id = itens.produto_id;


  ----------------------------------------------------
  -- 15. Retorna pedido criado
  ----------------------------------------------------

  return query
  select
    v_pedido_id,
    v_codigo_acesso,
    v_subtotal,
    v_taxa_entrega,
    v_total;

end;
$function$;


-- ============================================================
-- 12. CRIA PEDIDO COM FIDELIDADE
-- ============================================================
-- Sobrecarga:
--
-- função atual de 11 parâmetros
-- +
-- p_pontos_fidelidade integer
--
-- Toda a criação do pedido, estoque e resgate ocorre
-- dentro da mesma transação PostgreSQL.
-- ============================================================

CREATE OR REPLACE FUNCTION public.criar_pedido_com_estoque(
  p_nome text,
  p_telefone text,
  p_cep text,
  p_rua text,
  p_numero text,
  p_complemento text,
  p_bairro text,
  p_referencia text,
  p_forma_pagamento text,
  p_troco_para numeric,
  p_itens jsonb,
  p_pontos_fidelidade integer
)
RETURNS TABLE(
  pedido_id bigint,
  codigo_acesso uuid,
  subtotal numeric,
  taxa_entrega numeric,
  total numeric
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_resultado record;

  v_cliente_id bigint;

  v_saldo_atual integer;

  v_subtotal numeric;

  v_taxa_entrega numeric;

  v_taxa_cartao numeric;

  v_desconto numeric(12, 2);

  v_total_final numeric(12, 2);
BEGIN

  ----------------------------------------------------
  -- Valida pontos
  ----------------------------------------------------

  IF p_pontos_fidelidade IS NULL
     OR p_pontos_fidelidade < 0 THEN

    RAISE EXCEPTION
      'PONTOS_FIDELIDADE_INVALIDOS';

  END IF;


  IF MOD(p_pontos_fidelidade, 500) <> 0 THEN

    RAISE EXCEPTION
      'PONTOS_FIDELIDADE_DEVE_SER_MULTIPLO_DE_500';

  END IF;


  ----------------------------------------------------
  -- Usa função principal já existente
  ----------------------------------------------------

  SELECT *
  INTO v_resultado
  FROM public.criar_pedido_com_estoque(
    p_nome,
    p_telefone,
    p_cep,
    p_rua,
    p_numero,
    p_complemento,
    p_bairro,
    p_referencia,
    p_forma_pagamento,
    p_troco_para,
    p_itens
  );


  ----------------------------------------------------
  -- Pedido sem resgate
  ----------------------------------------------------

  IF p_pontos_fidelidade = 0 THEN

    RETURN QUERY
    SELECT
      v_resultado.pedido_id,
      v_resultado.codigo_acesso,
      v_resultado.subtotal,
      v_resultado.taxa_entrega,
      v_resultado.total;

    RETURN;

  END IF;


  ----------------------------------------------------
  -- Busca pedido recém-criado
  ----------------------------------------------------

  SELECT
    p.cliente_id,
    p.subtotal,
    p.taxa_entrega,
    p.taxa_cartao

  INTO
    v_cliente_id,
    v_subtotal,
    v_taxa_entrega,
    v_taxa_cartao

  FROM public.pedidos p
  WHERE p.id = v_resultado.pedido_id
  FOR UPDATE;


  IF NOT FOUND THEN

    RAISE EXCEPTION
      'PEDIDO_NAO_ENCONTRADO_APOS_CRIACAO:%',
      v_resultado.pedido_id;

  END IF;


  ----------------------------------------------------
  -- Bloqueia cliente e consulta saldo
  ----------------------------------------------------

  SELECT c.pontos_saldo
  INTO v_saldo_atual
  FROM public.clientes c
  WHERE c.id = v_cliente_id
  FOR UPDATE;


  IF NOT FOUND THEN

    RAISE EXCEPTION
      'CLIENTE_NAO_ENCONTRADO:%',
      v_cliente_id;

  END IF;


  ----------------------------------------------------
  -- Confere saldo
  ----------------------------------------------------

  IF v_saldo_atual < p_pontos_fidelidade THEN

    RAISE EXCEPTION
      'SALDO_PONTOS_INSUFICIENTE:%:%',
      v_saldo_atual,
      p_pontos_fidelidade;

  END IF;


  ----------------------------------------------------
  -- Calcula desconto
  ----------------------------------------------------

  v_desconto :=
    (p_pontos_fidelidade / 500) * 5;


  ----------------------------------------------------
  -- Fidelidade não paga taxas
  ----------------------------------------------------

  IF v_desconto > v_subtotal THEN

    RAISE EXCEPTION
      'DESCONTO_FIDELIDADE_SUPERA_SUBTOTAL:%:%',
      v_desconto,
      v_subtotal;

  END IF;


  ----------------------------------------------------
  -- Novo total
  ----------------------------------------------------

  v_total_final :=
      v_subtotal
    + v_taxa_entrega
    + v_taxa_cartao
    - v_desconto;


  ----------------------------------------------------
  -- Consome pontos
  ----------------------------------------------------

  UPDATE public.clientes
  SET pontos_saldo =
    pontos_saldo - p_pontos_fidelidade
  WHERE id = v_cliente_id;


  ----------------------------------------------------
  -- Atualiza pedido
  ----------------------------------------------------

  UPDATE public.pedidos
  SET
    desconto_fidelidade =
      v_desconto,

    pontos_fidelidade_usados =
      p_pontos_fidelidade,

    total =
      v_total_final

  WHERE id = v_resultado.pedido_id;


  ----------------------------------------------------
  -- Registra resgate no extrato
  ----------------------------------------------------

  INSERT INTO public.fidelidade_movimentacoes (
    cliente_id,
    pedido_id,
    tipo,
    pontos,
    valor_referencia,
    observacao
  )
  VALUES (
    v_cliente_id,
    v_resultado.pedido_id,
    'resgate',
    -p_pontos_fidelidade,
    v_desconto,

    'Resgate de fidelidade no pedido #'
      || v_resultado.pedido_id
      || ': R$ '
      || to_char(
        v_desconto,
        'FM999999990.00'
      )
      || ' de desconto'
  );


  ----------------------------------------------------
  -- Retorno
  ----------------------------------------------------

  RETURN QUERY
  SELECT
    v_resultado.pedido_id,
    v_resultado.codigo_acesso,
    v_subtotal,
    v_taxa_entrega,
    v_total_final;

END;
$function$;


