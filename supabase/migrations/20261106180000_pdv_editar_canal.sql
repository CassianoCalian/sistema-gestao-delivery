BEGIN;

ALTER TABLE public.pdv_vendas
  ADD COLUMN IF NOT EXISTS dados_entrega jsonb;

ALTER TABLE public.pdv_vendas
  DROP CONSTRAINT IF EXISTS pdv_vendas_tipo_atendimento_check;

ALTER TABLE public.pdv_vendas
  ADD CONSTRAINT pdv_vendas_tipo_atendimento_check
  CHECK (tipo_atendimento IN ('balcao', 'delivery'));

ALTER TABLE public.pdv_vendas
  DROP CONSTRAINT IF EXISTS pdv_vendas_delivery_endereco_check;

ALTER TABLE public.pdv_vendas
  ADD CONSTRAINT pdv_vendas_delivery_endereco_check
  CHECK (tipo_atendimento <> 'delivery' OR (
    coalesce(jsonb_typeof(dados_entrega) = 'object', false)
    AND nullif(btrim(dados_entrega->>'rua'), '') IS NOT NULL
    AND nullif(btrim(dados_entrega->>'numero'), '') IS NOT NULL
  ));

CREATE TABLE IF NOT EXISTS public.pdv_venda_alteracoes_canal (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venda_id bigint NOT NULL REFERENCES public.pdv_vendas(id) ON DELETE RESTRICT,
  criado_em timestamptz NOT NULL DEFAULT now(),
  canal_anterior text NOT NULL,
  canal_novo text NOT NULL,
  operador_email text NOT NULL
);

ALTER TABLE public.pdv_venda_alteracoes_canal ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.pdv_venda_alteracoes_canal
  FROM PUBLIC, anon, authenticated;

GRANT ALL ON public.pdv_venda_alteracoes_canal TO service_role;

GRANT USAGE, SELECT ON SEQUENCE
  public.pdv_venda_alteracoes_canal_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.pdv_alterar_canal_venda(
  p_venda_id bigint,
  p_tipo text,
  p_dados_entrega jsonb,
  p_operador_email text
)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE
  v_venda record;
BEGIN
  IF auth.role() IS DISTINCT FROM 'service_role' THEN
    RAISE EXCEPTION 'SEM_PERMISSAO';
  END IF;

  IF p_venda_id IS NULL OR p_venda_id <= 0 OR
     p_tipo IS NULL OR p_tipo NOT IN ('balcao','delivery') OR
     nullif(btrim(p_operador_email),'') IS NULL THEN
    RAISE EXCEPTION 'DADOS_INVALIDOS';
  END IF;

  IF p_tipo = 'delivery' AND (
    p_dados_entrega IS NULL OR
    jsonb_typeof(p_dados_entrega) <> 'object' OR
    nullif(btrim(p_dados_entrega->>'rua'),'') IS NULL OR
    nullif(btrim(p_dados_entrega->>'numero'),'') IS NULL OR
    length(p_dados_entrega::text) > 2500
  ) THEN
    RAISE EXCEPTION 'ENDERECO_INVALIDO';
  END IF;

  SELECT v.id, v.status, v.turno_id,
         v.tipo_atendimento, v.dados_entrega
  INTO v_venda
  FROM public.pdv_vendas v
  WHERE v.id = p_venda_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'VENDA_NAO_ENCONTRADA';
  END IF;

  IF v_venda.status <> 'concluida' THEN
    RAISE EXCEPTION 'VENDA_NAO_EDITAVEL';
  END IF;

  PERFORM t.id
  FROM public.pdv_turnos t
  JOIN public.pdv_caixas c ON c.id=t.caixa_id
  WHERE t.id=v_venda.turno_id
    AND t.status='aberto'
    AND c.codigo='principal'
  FOR UPDATE OF t;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'TURNO_ENCERRADO';
  END IF;

  UPDATE public.pdv_vendas
  SET tipo_atendimento=p_tipo,
      dados_entrega=CASE
        WHEN p_tipo='delivery' THEN p_dados_entrega
        ELSE NULL
      END
  WHERE id=p_venda_id;

  IF v_venda.tipo_atendimento IS DISTINCT FROM p_tipo
     OR v_venda.dados_entrega IS DISTINCT FROM
        (CASE WHEN p_tipo='delivery' THEN p_dados_entrega ELSE NULL END) THEN
    INSERT INTO public.pdv_venda_alteracoes_canal (
      venda_id, canal_anterior, canal_novo, operador_email
    ) VALUES (
      p_venda_id, v_venda.tipo_atendimento,
      p_tipo, lower(btrim(p_operador_email))
    );
  END IF;
END;
$fn$;

REVOKE ALL ON FUNCTION
  public.pdv_alterar_canal_venda(bigint,text,jsonb,text)
  FROM PUBLIC,anon,authenticated;

GRANT EXECUTE ON FUNCTION
  public.pdv_alterar_canal_venda(bigint,text,jsonb,text)
  TO service_role;

COMMIT;